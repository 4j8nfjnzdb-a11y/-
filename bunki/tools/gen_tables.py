#!/usr/bin/env python3
"""Writes core/bk_tables.h: the constant tables of the engine.

Tables are generated here, on the computer, and compiled in as constants, so that the
desktop build, fm1-emu and the FM-1 all read the very same numbers (no sin() or log() at
run time, no floating point in the engine).

  python3 tools/gen_tables.py > core/bk_tables.h
"""
import math

SIN_N = 1024          # one cycle; one guard entry after it for the interpolation
LOG_N = 256           # log2(1 + i/256), i = 0..256

print("/* generated by tools/gen_tables.py: do not edit */")
print("#ifndef BK_TABLES_H")
print("#define BK_TABLES_H")
print("#include <stdint.h>")
print()
print("/* sin(2 pi i / %d), Q15, i = 0..%d (the last entry repeats the first) */" % (SIN_N, SIN_N))
vals = [int(round(32767 * math.sin(2 * math.pi * i / SIN_N))) for i in range(SIN_N + 1)]
print("static const int16_t BK_SIN[%d] = {" % (SIN_N + 1))
for i in range(0, len(vals), 12):
    print("    " + ", ".join("%d" % v for v in vals[i:i + 12]) + ",")
print("};")
print()
print("/* log2(1 + i / %d), Q16, i = 0..%d */" % (LOG_N, LOG_N))
lv = [int(round(65536 * math.log2(1 + i / LOG_N))) for i in range(LOG_N + 1)]
print("static const uint32_t BK_LOG2_1P[%d] = {" % (LOG_N + 1))
for i in range(0, len(lv), 10):
    print("    " + ", ".join("%du" % v for v in lv[i:i + 10]) + ",")
print("};")
print()
print("#endif")
