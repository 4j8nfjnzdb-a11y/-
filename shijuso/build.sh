#!/bin/sh
# Wraps app.html (artifact body) into a standalone page for direct browser use, and writes worklet.js:
# the audio-thread engine (DSPLIB + the processor) as its own file, published next to the page.
cd "$(dirname "$0")"
{ printf '<!doctype html><html lang="ja"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body style="margin:0">\n'; cat app.html; printf '\n</body></html>\n'; } > index.html
node -e '
const fs=require("fs"),s=fs.readFileSync("app.html","utf8");
const cut=(a,b)=>s.slice(s.indexOf(a),s.indexOf(b)).trim();
fs.writeFileSync("worklet.js","// Generated by build.sh from app.html: the audio-thread engine.\nconst LIB=("+cut("function DSPLIB(){","//@@DSP-END")+")();\n("+cut("function PROCSRC(){","//@@PROC-END")+")();\n");'
